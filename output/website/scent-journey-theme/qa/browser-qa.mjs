import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {chromium} from 'playwright-core';
const root=path.dirname(fileURLToPath(import.meta.url));
const base=process.env.PREVIEW_URL||'http://127.0.0.1:4208';
const report={timestamp:new Date().toISOString(),base,checks:[],failures:[],consoleErrors:[],screenshots:[],limits:['Local LiquidJS preview; no checkout or live writes.','Public metafields are not exposed; actual theme supplied-copy fallback is used. Finder metadata is unavailable in the read-only public snapshot; eligibility and scoring are separately exercised with fixtures.','Original transparent logos and supplied Cenzo Flare Bold / Helvetica Now Text Regular fonts are tracked in ASSET-AUDIT.md.']};
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
process.on('uncaughtException',async error=>{report.failures.push({label:'Browser suite fatal error',detail:error.message});await fs.writeFile(path.join(root,'browser-report.json'),JSON.stringify(report,null,2));await browser.close();console.error(error.message);process.exit(1);});
const context=await browser.newContext({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const page=await context.newPage();
page.on('pageerror',e=>report.consoleErrors.push(e.message));
const check=(label,pass,detail)=>{(pass?report.checks:report.failures).push({label,...(detail?{detail}:{})});};
const capture=async(name,fullPage=false)=>{const file=path.join(root,'screenshots',name+'.png');await fs.mkdir(path.dirname(file),{recursive:true});await page.screenshot({path:file,fullPage});report.screenshots.push(path.relative(root,file));};
const previewReport=await(await fetch(base+'/preview-report.json')).json();
for(const theme of ['light','dark']) {
 for(const entry of previewReport.routes) {
  const response=await page.goto(base+entry.route+'?visual_theme='+theme,{waitUntil:'domcontentloaded'});
  await page.waitForTimeout(90);
  const state=await page.evaluate(()=>({theme:document.documentElement.dataset.theme,h1:document.querySelectorAll('h1').length,overflow:document.documentElement.scrollWidth>window.innerWidth+2,title:document.title,missingAlts:[...document.images].filter(i=>!i.hasAttribute('alt')).length}));
  check(`${theme} ${entry.route}: HTTP success`,response.status()===200);
  check(`${theme} ${entry.route}: correct theme`,state.theme===theme,state.theme);
  check(`${theme} ${entry.route}: one H1`,state.h1===1,String(state.h1));
  check(`${theme} ${entry.route}: no desktop horizontal overflow`,!state.overflow);
  check(`${theme} ${entry.route}: image alt attributes`,state.missingAlts===0,String(state.missingAlts));
 }
 await page.goto(base+'/?visual_theme='+theme,{waitUntil:'networkidle'});
 await capture('home-'+theme+'-desktop',true);
 await page.locator('[data-sj-open-search]').click();
 check(`${theme}: search dialog opens`,await page.locator('#sj-search-dialog').evaluate(el=>el.open));
 await page.locator('[data-sj-predictive-input]').fill('Oud');
 await page.waitForSelector('[data-sj-search-option]');
 check(`${theme}: predictive search finds real products`,await page.locator('[data-sj-search-option]').count()>=2);
 await page.keyboard.press('ArrowDown');
 check(`${theme}: predictive search keyboard selection`,Boolean(await page.locator('[data-sj-predictive-input]').getAttribute('aria-activedescendant')));
 await page.keyboard.press('Escape');
 check(`${theme}: first Escape clears search suggestions`,await page.locator('[data-sj-search-option]').count()===0);
 await page.keyboard.press('Escape');
 check(`${theme}: search Escape closes dialog`,!await page.locator('#sj-search-dialog').evaluate(el=>el.open));
 await page.locator('[data-sj-open-cart]').click();
 check(`${theme}: bag dialog opens`,await page.locator('#sj-cart-drawer').evaluate(el=>el.open));
 check(`${theme}: current cart correctly empty`,(await page.locator('#sj-cart-drawer').innerText()).includes('Your bag is waiting'));
 await page.keyboard.press('Escape');
 check(`${theme}: bag Escape closes dialog`,!await page.locator('#sj-cart-drawer').evaluate(el=>el.open));
 await page.goto(base+'/products/mojito-metallique?visual_theme='+theme,{waitUntil:'networkidle'});
 const before=await page.locator('[data-sj-gallery]').boundingBox();
 const panel=page.locator('[data-sj-product-info]');
 const scrollability=await panel.evaluate(el=>({overflow:getComputedStyle(el).overflowY,client:el.clientHeight,height:el.scrollHeight}));
 check(`${theme}: desktop information scroll container`,scrollability.overflow==='auto'&&scrollability.height>scrollability.client,JSON.stringify(scrollability));
 await panel.evaluate(el=>el.scrollTop=400);
 await page.waitForTimeout(100);
 const after=await page.locator('[data-sj-gallery]').boundingBox();
 check(`${theme}: gallery fixed while information scrolls`,Math.abs(before.y-after.y)<1);
 check(`${theme}: panel keyboard focusable`,await panel.getAttribute('tabindex')==='0');
 await page.locator('[data-sj-gallery-next]').click();
 check(`${theme}: next gallery media`,await page.locator('[data-sj-thumbnail]').nth(1).getAttribute('aria-pressed')==='true');
 await page.locator('[data-sj-gallery]').focus();await page.keyboard.press('ArrowRight');
 check(`${theme}: keyboard gallery media`,await page.locator('[data-sj-thumbnail]').nth(2).getAttribute('aria-pressed')==='true');
 check(`${theme}: verified sold out state`,await page.locator('[data-sj-add]').isDisabled());
 await panel.evaluate(el=>el.scrollTop=0);await page.waitForFunction(()=>getComputedStyle(document.querySelector('[data-sj-media].is-active')).opacity==='1');await capture('product-'+theme+'-desktop');
 await page.locator('[data-sj-media].is-active [data-sj-zoom]').click();
 check(`${theme}: image zoom opens`,await page.locator('[data-sj-zoom-dialog]').evaluate(el=>el.open));
 await page.keyboard.press('Escape');check(`${theme}: escape closes zoom`,!await page.locator('[data-sj-zoom-dialog]').evaluate(el=>el.open));
 await page.goto(base+'/pages/scent-finder?visual_theme='+theme,{waitUntil:'domcontentloaded'});
 check(`${theme}: finder does not invent available catalog`,(await page.locator('[data-sj-finder-data]').textContent()).trim()==='[]'||JSON.parse(await page.locator('[data-sj-finder-data]').textContent()).length===0);
 await capture('finder-'+theme+'-desktop',true);
 await page.setViewportSize({width:390,height:844});
 for(const route of ['/','/collections/womens-perfume','/products/mojito-metallique','/cart','/pages/scent-finder','/search']){
  await page.goto(base+route+'?visual_theme='+theme,{waitUntil:'domcontentloaded'});await page.waitForTimeout(150);
  check(`${theme} ${route}: no mobile horizontal overflow`,await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2));
 }
 await page.goto(base+'/products/mojito-metallique?visual_theme='+theme,{waitUntil:'networkidle'});
 const mobile=await page.locator('[data-sj-product-info]').evaluate(el=>({overflow:getComputedStyle(el).overflowY,height:el.clientHeight,scroll:el.scrollHeight}));
 check(`${theme}: mobile product info uses natural scrolling`,mobile.overflow!=='auto'||mobile.height===mobile.scroll,JSON.stringify(mobile));
 await capture('product-'+theme+'-mobile',true);
 await page.goto(base+'/?visual_theme='+theme,{waitUntil:'networkidle'});await capture('home-'+theme+'-mobile',true);
 await page.setViewportSize({width:1440,height:1000});
}
check('No uncaught browser JS errors',report.consoleErrors.length===0,JSON.stringify(report.consoleErrors));
await fs.writeFile(path.join(root,'browser-report.json'),JSON.stringify(report,null,2));
await browser.close();console.log(JSON.stringify({passed:report.checks.length,failures:report.failures,consoleErrors:report.consoleErrors,screenshots:report.screenshots},null,2));
if(report.failures.length)process.exitCode=1;
